import os

ROOMS_DIR = "assets/rooms"
os.makedirs(ROOMS_DIR, exist_ok=True)

# 10 columns x 8 rows
# 0: empty
# 1: wall
# L: ladder
# P: ladder top
# 4: 25% pushblock
# 5/6: 5x3 obstacle block

def write_template(type_id, index, grid_lines):
    # Ensure it's 8 rows of 10 chars
    assert len(grid_lines) == 8
    for line in grid_lines:
        assert len(line) == 10
    
    filename = os.path.join(ROOMS_DIR, f"type{type_id}_{index}.txt")
    with open(filename, "w") as f:
        f.write("\n".join(grid_lines))

